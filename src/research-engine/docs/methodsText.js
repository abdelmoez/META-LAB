/**
 * methodsText.js — prompt42 Task 8. Pure, network-free generator for the Methods
 * section that ships inside the one-click journal-submission package.
 *
 * It does NOT invent data: every sentence is built from a context object the caller
 * assembles from the project's ACTUAL settings + the live meta-analysis result
 * (model, measure, heterogeneity, k, software version, GRADE). Where a field is
 * missing it is omitted or marked "[not recorded]" rather than fabricated — the
 * researcher fills those gaps. Statistical-method statements describe what the
 * engine ACTUALLY ran (inverse-variance fixed effect; DerSimonian–Laird random
 * effects; optional Hartung–Knapp–Sidik–Jonkman), mirroring the report footer.
 *
 * Pure + exported for unit tests (tests/unit/methodsText.test.js).
 */

import { describeSynthesisModel } from '../manuscript/analysisDescribe.js';

const PLACEHOLDER = '[not recorded — please complete]';

function clean(s) { return String(s == null ? '' : s).trim(); }
function line(parts) { return parts.filter(Boolean).join(''); }

/** Verbatim researcher text → bullet lines (split on newlines; leading bullet
 *  glyphs stripped so "• item" stored by CriteriaList doesn't double-bullet). */
function bulletLines(text) {
  return String(text == null ? '' : text)
    .split(/\r?\n/)
    .map((l) => l.replace(/^[\s•*·-]+/, '').trim())
    .filter(Boolean);
}

/**
 * @param {object} ctx
 *   projectName, generatedAt(string)
 *   pico {question,P,I,C,O}
 *   eligibility {incl,excl,studyDesign,timeframe}  73.md Part 8 — verbatim
 *     researcher criteria rendered as bullet lists (omitted when absent, so
 *     legacy callers get byte-identical output)
 *   databases(string), dateSearched(string), registration(string)
 *   searchMethodsText(string)  server-composed search paragraph (search-builder
 *     methods-text endpoint); replaces the generic sentence when present
 *   prisma {identified,deduped,screened,excludedFullText,included}
 *   screening {reviewers(number), blind(bool), conflictResolution(string)}
 *   measure(string label), model('fixed'|'random'), tau2Method('DL'|'REML'|…),
 *   hksj(bool)
 *   k(number), heterogeneity {I2,tau2,Q,Qdf,Qp}, predInterval(bool)
 *   outcomes(string[]), robTool(string), grade(bool), software(string)
 * @returns {string} GitHub-flavoured Markdown
 */
export function buildMethodsMarkdown(ctx = {}) {
  const c = ctx || {};
  const pico = c.pico || {};
  const het = c.heterogeneity || {};
  const prisma = c.prisma || {};
  const screening = c.screening || {};
  const out = [];

  out.push(`# Methods — ${clean(c.projectName) || 'Systematic review and meta-analysis'}`);
  out.push('');
  out.push(`_Auto-generated by PecanRev${c.software ? ` (${clean(c.software)})` : ''}${c.generatedAt ? ` on ${clean(c.generatedAt)}` : ''}. Review and edit before submission; bracketed placeholders need your input._`);
  out.push('');

  // ── Protocol & registration ────────────────────────────────────────────────
  out.push('## Protocol and registration');
  out.push(c.registration
    ? `This review was registered/recorded as: ${clean(c.registration)}.`
    : `The review protocol registration (e.g. PROSPERO) is ${PLACEHOLDER}.`);
  out.push('');

  // ── Eligibility (PICO) ──────────────────────────────────────────────────────
  out.push('## Eligibility criteria (PICO)');
  if (pico.question) out.push(`**Review question.** ${clean(pico.question)}`);
  out.push(`- **Population:** ${clean(pico.P) || PLACEHOLDER}`);
  out.push(`- **Intervention/Exposure:** ${clean(pico.I) || PLACEHOLDER}`);
  out.push(`- **Comparator:** ${clean(pico.C) || PLACEHOLDER}`);
  out.push(`- **Outcomes:** ${clean(pico.O) || PLACEHOLDER}`);
  // 73.md Part 8 — researcher-entered eligibility detail, VERBATIM (each line
  // only renders when the project actually has the field; legacy ctx unchanged).
  const elig = c.eligibility || {};
  if (clean(elig.studyDesign)) out.push(`- **Study designs:** ${clean(elig.studyDesign)}`);
  if (clean(elig.timeframe)) out.push(`- **Time frame:** ${clean(elig.timeframe)}`);
  const inclLines = bulletLines(elig.incl);
  if (inclLines.length) {
    out.push('');
    out.push('**Inclusion criteria.**');
    for (const l of inclLines) out.push(`- ${l}`);
  }
  const exclLines = bulletLines(elig.excl);
  if (exclLines.length) {
    out.push('');
    out.push('**Exclusion criteria.**');
    for (const l of exclLines) out.push(`- ${l}`);
  }
  out.push('');

  // ── Information sources & search ────────────────────────────────────────────
  out.push('## Information sources and search strategy');
  // A server-composed search paragraph (real per-database strategy) wins over
  // the generic sentence; never both.
  //
  // 101.md §1/§17 — `databases` and `dateSearched` MUST arrive from the search
  // EXECUTION record (searchProvenance.deriveSearchProvenance), never from the
  // settings checkboxes. When the project has no execution record we emit a
  // placeholder rather than naming databases we cannot prove were searched.
  out.push(clean(c.searchMethodsText) || line([
    'We searched ',
    c.databases ? clean(c.databases) : PLACEHOLDER,
    c.dateSearched ? ` (last searched ${clean(c.dateSearched)})` : '',
    '. The full search strategy for at least one database is reported in the search-strategy export.',
  ]));
  out.push('');

  // ── Study selection / screening ─────────────────────────────────────────────
  out.push('## Study selection');
  // 101.md §17 — this paragraph previously asserted "by independent reviewers"
  // and "Disagreements were resolved by discussion" UNCONDITIONALLY, i.e. even
  // for a single-reviewer project that never recorded a conflict process. Those
  // are methodological claims a reader would rely on, so each clause now appears
  // only when the project record supports it, and the gap is made visible.
  const revN = Number(screening.reviewers);
  const reviewerClause = Number.isFinite(revN) && revN >= 2
    ? `by ${revN} independent reviewers`
    : (Number.isFinite(revN) && revN === 1 ? 'by a single reviewer' : '');
  out.push(line([
    'Records were de-duplicated and screened ',
    reviewerClause || PLACEHOLDER,
    reviewerClause && screening.blind ? ', blinded to each other\'s decisions' : '',
    ', first on title/abstract and then on full text against the eligibility criteria. ',
    screening.conflictResolution
      ? `Disagreements were resolved by ${clean(screening.conflictResolution)}. `
      : (Number.isFinite(revN) && revN >= 2 ? `Disagreement resolution: ${PLACEHOLDER}. ` : ''),
    'The selection process is summarised in the PRISMA 2020 flow diagram included in this package.',
  ]));
  if (prisma.identified != null || prisma.included != null) {
    out.push('');
    out.push(line([
      'In total, ',
      prisma.identified != null ? `${prisma.identified} records were identified` : 'records were identified',
      prisma.deduped != null ? `, ${prisma.deduped} duplicates removed` : '',
      prisma.included != null ? `, and ${prisma.included} studies were included in the review.` : '.',
    ]));
  }
  out.push('');

  // ── Data extraction ─────────────────────────────────────────────────────────
  out.push('## Data extraction');
  // 101.md §17 — the old sentence enumerated the extracted fields as fact. Name
  // only the fields the project's own extraction form actually defines; describe
  // the platform guarantee (raw inputs retained) separately, because that one IS
  // true of every project.
  const extractedFields = (Array.isArray(c.extractionFields) ? c.extractionFields : [])
    .map(clean).filter(Boolean);
  out.push(line([
    extractedFields.length
      ? `Study-level data (${extractedFields.join(', ')}) were extracted into a structured form`
      : 'Study-level data were extracted into a structured form',
    '; raw inputs were retained so every derived value is auditable. ',
    'The extracted study table is included in this package.',
  ]));
  out.push('');

  // ── Risk of bias ────────────────────────────────────────────────────────────
  out.push('## Risk of bias');
  // 101.md §27 — describe the tools ACTUALLY used, not the one selected in a
  // settings dropdown. `robUsage.tools` carries only instruments with at least
  // one real assessment; when several were used for different designs, name each
  // with the designs it covered rather than collapsing them into one claim.
  //
  // Precedence mirrors the search facts: `robUsage` (real completed assessments)
  // is authoritative when supplied; a caller that has not been migrated yet still
  // gets the legacy `robTool` sentence unchanged, so no existing export regresses.
  const usage = c.robUsage || null;
  const usedTools = usage && Array.isArray(usage.tools)
    ? usage.tools.filter((t) => t && Number(t.count) > 0) : [];
  if (!usage && c.robTool) {
    // Legacy path — the project's SELECTED instrument, byte-identical to pre-101
    // output for callers that do not yet supply usage.
    out.push(`Risk of bias was assessed at the outcome level using ${clean(c.robTool)}; each domain judgement was recorded with its supporting rationale.`);
  } else if (usedTools.length > 1) {
    out.push('Methodological quality was assessed using the instrument appropriate to each study design:');
    for (const t of usedTools) {
      out.push(`- ${clean(t.label)}${t.designLabel ? ` for ${clean(t.designLabel)}` : ''} (${t.count} ${Number(t.count) === 1 ? 'study' : 'studies'}).`);
    }
    out.push('');
    out.push('Each judgement was recorded with its supporting rationale.');
  } else if (usedTools.length === 1) {
    const t = usedTools[0];
    out.push(line([
      `Methodological quality was assessed using ${clean(t.label)}`,
      t.designLabel ? ` for ${clean(t.designLabel)}` : '',
      `; each ${t.scoring === 'stars' ? 'item' : 'domain'} judgement was recorded with its supporting rationale.`,
    ]));
  } else {
    // No completed assessment — say so instead of claiming the selected tool was used.
    out.push(`Risk of bias / quality assessment tool: ${PLACEHOLDER} (no assessment has been completed in this project yet).`);
  }
  out.push('');

  // ── Statistical synthesis ───────────────────────────────────────────────────
  out.push('## Statistical analysis');
  // Shared wording (analysisDescribe.js) — byte-identical for fixed / DL-random;
  // names the configured τ² estimator otherwise.
  const synth = describeSynthesisModel({ model: c.model, tau2Method: c.tau2Method });
  const modelLabel = synth.methodsPhrase;
  out.push(line([
    'Effect sizes',
    c.measure ? ` (${clean(c.measure)})` : '',
    ' were pooled using ',
    modelLabel,
    c.hksj ? ', with the Hartung–Knapp–Sidik–Jonkman adjustment to the confidence interval' : '',
    '. ',
    Number.isFinite(Number(c.k)) ? `A total of ${c.k} studies contributed to the primary synthesis. ` : '',
    'Ratio measures were pooled on the log scale and back-transformed for presentation.',
  ]));
  out.push('');
  out.push(line([
    'Heterogeneity was quantified with the I² statistic and τ² (between-study variance), and tested with Cochran\'s Q. ',
    het.I2 != null ? `For the primary outcome, I² = ${het.I2}%` : '',
    het.tau2 != null ? `, τ² = ${het.tau2}` : '',
    (het.Q != null) ? `, Q = ${het.Q}${het.Qdf != null ? ` (df = ${het.Qdf})` : ''}${het.Qp != null ? `, p = ${het.Qp}` : ''}` : '',
    (het.I2 != null || het.Q != null) ? '. ' : '',
    c.predInterval ? 'A 95% prediction interval is reported for the random-effects estimate. ' : '',
  ]).trim() || 'Heterogeneity was quantified with I² and τ² and tested with Cochran\'s Q.');
  out.push('');
  if (Array.isArray(c.outcomes) && c.outcomes.length) {
    out.push(`A separate forest plot was produced for each outcome: ${c.outcomes.map(clean).filter(Boolean).join('; ')}.`);
    out.push('');
  }

  // ── Certainty (GRADE) ───────────────────────────────────────────────────────
  out.push('## Certainty of evidence');
  out.push(c.grade
    ? 'The certainty of evidence for each outcome was rated using the GRADE approach (risk of bias, inconsistency, indirectness, imprecision and publication bias).'
    : `Certainty of evidence (GRADE) assessment: ${PLACEHOLDER}.`);
  out.push('');

  // ── Software ────────────────────────────────────────────────────────────────
  out.push('## Software');
  const randomImpl = synth.tau2Method === 'DL'
    ? 'DerSimonian–Laird random effects'
    : `random effects with the ${synth.estimatorPhrase} τ² estimator`;
  out.push(line([
    'Screening, data extraction, meta-analysis and figures were produced in PecanRev',
    c.software ? ` (${clean(c.software)})` : '',
    `. Statistical methods implemented: inverse-variance fixed effect and ${randomImpl}`,
    c.hksj ? ', with Hartung–Knapp–Sidik–Jonkman adjustment' : '',
    '. Verify all numbers against your primary analysis before submission.',
  ]));
  out.push('');

  return out.join('\n');
}

export default buildMethodsMarkdown;
